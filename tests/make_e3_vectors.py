"""Escrow test vectors: real claims and submissions, with the hashes and the chain the judge contract
computes, so the Foundry tests check that the escrow computes the same.

Each vector runs through the judge contract (simulated SDK, tests/judge_v2_stub_run.py): the final
verdict carries the chain the judge saw, and the escrow has to end with that same chain. Writes
evm/test/JudgeVectors.sol (bytes in hex, so quotes are not a problem).

Usage: LACRE_DIR=<lacre clone> py -3.12 tests/make_e3_vectors.py
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tests"))
import judge_v2_stub_run as H  # noqa: E402

PAID = H.unix("2026-09-01", 12)
CLAIMED = H.unix("2026-09-10", 12)
OUT = ROOT / "evm" / "test" / "JudgeVectors.sol"


def base(order, event, extra):
    c = {"v": "claim-v1", "order_ref": H.mail_v1.order_ref(order), "order_number": order, "buyer": H.BUYER,
         "merchant": H.MERCHANT, "amount_cents": 5000, "paid_at": PAID, "claimed_at": CLAIMED,
         "terms_hash": H.TERMS_HASH, "event": event}
    c.update(extra)
    return c


def vectors():
    out = []
    # V1: late, two emails from the buyer (email judge).
    w = H.World("mail")
    c = base("DS-100231", "late", {})
    steps = [("buyer", w.ev("E01")), ("buyer", w.ev("E03"))]
    for _, s in steps:
        w.judge(c, [s], "2026-09-10T13:00:00Z", H.scripted({"type": "order_confirmed" if s is steps[0][1] else "delivered"}))
    out.append(("late", c, steps, w.verdict(c)))
    # V2: not_as_described with Spanish text, quotes and line breaks (on purpose); full closing round.
    w = H.World("subjective")
    c = base("DS-200001", "not_as_described", {
        "description": "Reloj Casio original, modelo F-91W. Tamaño \"grande\".", "account": "Es una copia.\nNo tiene grabado.",
        "promised": "original", "received": "sin grabado de Casio", "proof_kind": "", "proof": "",
        "delivered_date": "2026-09-07"})
    w.committee.lookup = H.scripted({"q1": "differs", "q2": "disputes_with_fact"})
    steps = [("merchant", H.response("Es original: factura 0012-4455, ¡revisada!")),
             ("relayer", H.marker("closing_open")),
             ("buyer", {"party": "buyer", "kind": "closing_proof",
                        "content": {"proof_kind": "label", "proof": "Tapa trasera: sin grabado de Casio"}}),
             ("merchant", {"party": "merchant", "kind": "closing_response", "content": "Seguimos diciendo que es original."})]
    for i, (_, s) in enumerate(steps):
        w.judge(c, [s], "2026-09-10T13:00:00Z")
    out.append(("not_as_described", c, steps, w.verdict(c)))
    # V3: not_delivered without an answer: no_response marker.
    w = H.World("subjective")
    c = base("DS-300001", "not_delivered", {"account": "Nunca llegó.", "promised_date": "2026-08-25"})
    steps = [("anyone", H.marker("no_response"))]
    w.judge(c, [steps[0][1]], "2026-09-13T13:00:00Z", H.scripted({}))
    out.append(("not_delivered", c, steps, w.verdict(c)))
    return out


def hexb(text):
    return 'hex"%s"' % text.encode("ascii").hex()


def main():
    lines = ["// SPDX-License-Identifier: MIT",
             "// Generated by tests/make_e3_vectors.py from the judge contract. Do not edit by hand.",
             "pragma solidity 0.8.28;", "", "library JudgeVectors {",
             "    uint64 internal constant PAID = %d;" % PAID, "    uint64 internal constant CLAIMED = %d;" % CLAIMED,
             # 64 digits: a 40-digit literal would be an address and Solidity requires its checksum.
             "    address internal constant BUYER = address(uint160(uint256(0x%064x)));" % int(H.BUYER, 16),
             "    address internal constant MERCHANT = address(uint160(uint256(0x%064x)));" % int(H.MERCHANT, 16),
             "    bytes32 internal constant TERMS = %s;" % H.TERMS_HASH, ""]
    summary = []
    for i, (name, c, steps, v) in enumerate(vectors()):
        text = H.cj(c)
        h = H.sha(text)
        chain = H.chain0(h)
        lines += ["    // V%d: %s" % (i + 1, name), "    bytes32 internal constant V%d_REF = %s;" % (i + 1, c["order_ref"]),
                  "    bytes internal constant V%d_CLAIM = %s;" % (i + 1, hexb(text)),
                  "    bytes32 internal constant V%d_CLAIM_HASH = %s;" % (i + 1, h),
                  "    bytes32 internal constant V%d_CHAIN0 = %s;" % (i + 1, chain)]
        actors = []
        for j, (actor, s) in enumerate(steps):
            raw = H.cj(s)
            chain = H.fold(chain, raw)
            lines += ["    bytes internal constant V%d_S%d = %s;" % (i + 1, j + 1, hexb(raw)),
                      "    bytes32 internal constant V%d_C%d = %s;" % (i + 1, j + 1, chain)]
            actors.append(actor)
        assert v and v["chain"] == chain and v["claim_hash"] == h, (name, v)
        lines += ["    bytes32 internal constant V%d_JUDGE_CHAIN = %s; // judge verdict: %s" % (
            i + 1, v["chain"], v["outcome"]), ""]
        summary.append("V%d %s: %d submissions (%s), verdict %s, judge chain = computed chain" % (
            i + 1, name, len(steps), ", ".join(actors), v["outcome"]))
    lines.append("}")
    OUT.write_text("\n".join(lines) + "\n", encoding="ascii", newline="\n")
    print(OUT)
    print("\n".join(summary))


if __name__ == "__main__":
    main()
